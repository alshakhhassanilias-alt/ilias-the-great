const main = events.find((e) => e.name === 'thread_name' && e.args.name === 'CrRendererMain');
const tid = main?.tid;
const agg = new Map();
for (const e of events) if (e.tid === tid && e.ph === 'X' && e.dur) agg.set(e.name, (agg.get(e.name) || 0) + e.dur / 1000);
[...agg].sort((a, b) => b[1] - a[1]).slice(0, 25).forEach(([k, v]) => console.log(v.toFixed(0).padStart(7), k));
