import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const pg = await b.newPage({ viewport: { width: 1440, height: 900 } });
pg.on('pageerror', (e) => console.log('ERR', e.message));
await pg.addInitScript(() => { localStorage.setItem('wo-tutorial-1', '1'); });
await pg.goto('http://localhost:4173');
const out = '/tmp/claude-0/scratch';
await pg.click('.mode-card:has-text("Legacy")');
await pg.fill('input[type=search]', 'Poland'); await pg.click('.picklist button:has-text("Poland")');
await pg.waitForTimeout(400);
await pg.screenshot({ path: `${out}/L0.png` });
await pg.click('.start-side .foot .btn.primary');
await pg.waitForSelector('.app');
await pg.waitForTimeout(600);
await pg.screenshot({ path: `${out}/L1.png` });
await pg.click('.agenda-card >> nth=0'); await pg.click('.agenda-card >> nth=2'); await pg.click('.agenda-card >> nth=4');
await pg.waitForTimeout(300);
await pg.screenshot({ path: `${out}/L2.png` });
await pg.click('button:has-text("Swear to this agenda")');
await pg.evaluate(() => { const st = window.__store; for (let i = 0; i < 60; i++) st.stepOnce(); st.toasts = []; st.breaking = null; });
await pg.click('.legacy-chip');
await pg.waitForTimeout(400);
await pg.screenshot({ path: `${out}/L3.png` });
await pg.evaluate(() => { const st = window.__store; st.openDrawer('none'); for (let i = 0; i < 160; i++) { st.stepOnce(); for (const it of [...st.state.inbox]) st.act((g) => window.__resolve ? window.__resolve(g, it.uid) : ({ ok: true, message: '' }), true); } });
await pg.waitForTimeout(500);
await pg.screenshot({ path: `${out}/L4.png` });
console.log(await pg.evaluate(() => JSON.stringify({ term: window.__store.state.legacy.term, status: window.__store.state.legacy.status, terms: window.__store.state.legacy.terms.length, seen: window.__store.termSeen, rev: window.__store.state.stats.reviewTerm })));
await b.close();
