console.log('capital', I.capital);
import { supplyNet, stepCost } from '../src/sim/supply';
const net = supplyNet(s, geo, I.id);
for (const p of I.provinces) console.log(p, net.dist[p].toFixed(1), net.hub[p], net.prev[p]);
